import { test, expect } from "@playwright/test";
test("create, edit interview, refresh, filter, export and archive through the UI",async({page,request,baseURL})=>{
  test.skip(!baseURL,"Run with playwright.tracking.config.ts to use an isolated data directory.");
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/app/tracking");
  await page.getByRole("button",{name:"新增申请",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await dialog.getByLabel("公司 *",{exact:true}).fill("测试科技");
  await dialog.getByLabel("岗位 *",{exact:true}).fill("算法工程师");
  await dialog.getByLabel("当前状态").selectOption("applied");
  await dialog.getByRole("button",{name:"保存申请"}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("table")).toContainText("测试科技");
  await page.getByRole("button",{name:"查看 / 更新"}).click();
  await dialog.getByLabel("当前状态").selectOption("interviewing");
  await dialog.getByLabel("面试轮次").fill("二面");
  await dialog.getByLabel("跟进备注").fill("准备项目介绍");
  await dialog.getByRole("button",{name:"保存申请"}).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await expect(page.getByRole("table")).toContainText("面试中");
  await page.getByLabel("申请状态").selectOption("offer");
  await expect(page.getByText("暂时没有符合条件的申请")).toBeVisible();
  await page.getByRole("button",{name:"清空筛选"}).click();
  await page.getByRole("button",{name:"查看 / 更新"}).click();
  await expect(dialog.getByLabel("跟进备注")).toHaveValue("准备项目介绍");
  await expect(dialog.getByText("已投递 → 面试中")).toBeVisible();
  page.once("dialog",d=>d.accept());
  await dialog.getByRole("button",{name:"归档申请",exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await page.getByLabel("记录范围").selectOption("archived");
  await expect(page.getByRole("table")).toContainText("测试科技");
  const csv=await request.get("/api/tracking/export?archived=archived");expect(csv.status()).toBe(200);expect(await csv.text()).toContain("测试科技");
  expect(errors).toEqual([]);
});
